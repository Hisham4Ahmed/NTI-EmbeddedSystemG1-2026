/*

Alias Pointer in 2D -> 



int Arr[3][4] =
{
    {1,2,3,4},
    {10,20,30,40},
    {100,200,300,400},
},


Arr[1][2] ->  30 -> *(*(Arr+1)+2)

&Arr[1][2] -> *(Arr+1)+2



*/
#include <stdio.h>

int main()
{
    char Arr[3][4] =
    {
        {1,2,3,4},
        {10,20,30,40},
        {100,200,300,400},
    };  
    char Arr[3][4] =
    {
        {1,2,3,4},{10,20,30,40},{100,200,300,400},
    };  
    printf("1-Arr[1][2]=%d\n",Arr[1][2]);
    printf("2-Arr[1][2]=%d\n",*(*(Arr+1)+2));
    printf("1-&Arr[1][2]=%p\n",&Arr[1][2]);
    printf("2-&Arr[1][2]=%p\n",*(Arr+1)+2); 
    return 0 ; 
}